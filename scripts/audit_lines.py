"""
Can the stored lines be trusted as CLOSING lines? Run after scripts/fetch.py.

    .venv/bin/python scripts/audit_lines.py

Checks, per season and book:
  coverage     share of D1 games with a line, after the team crosswalk
  timing       share of lines Action Network last stored AFTER tip-off
  in-game?     a line stored after tip that had seen the game would be far more
               accurate than one stored before it. If the error is the same,
               the late timestamp is a bookkeeping write, not a live line.
  agreement    consensus vs FanDuel on games that have both (2023-24 on)
Writes research/line_audit.md.
"""
import numpy as np
import pandas as pd

from cbb import data, odds
from cbb.config import CURRENT_SEASON, RESEARCH

SEASONS = range(2020, CURRENT_SEASON)


def main():
    games, _ = data.load(SEASONS)
    fin = data.finals(games)
    out = ["# Line audit", "", "Generated by `scripts/audit_lines.py`.", "",
           "| season | book | games with line | coverage | stored after tip | error before tip | error after tip |",
           "|---|---|---|---|---|---|---|"]
    raw = pd.concat([pd.read_parquet(odds.season_file(s)) for s in SEASONS], ignore_index=True)
    cw = odds.load_crosswalk()
    for s in SEASONS:
        g = fin[fin.season == s][["game_id", "date", "home_id", "away_id", "tip", "home_score", "away_score"]]
        for book in ("consensus", "fanduel", "draftkings", "open"):
            a = odds.attach(g, raw, book, cw)
            a = a[a.home_spread.notna()]
            if not len(a):
                continue
            err = (a.home_score - a.away_score + a.home_spread).abs()
            late = a.captured > a.tip
            e_pre = err[~late].mean() if (~late).any() else np.nan
            e_post = err[late].mean() if late.any() else np.nan
            out.append(f"| {s} | {book} | {len(a)} | {len(a) / len(g):.1%} | {late.mean():.1%} | "
                       f"{e_pre:.2f} | {e_post:.2f} |")
    both = []
    for s in range(2024, CURRENT_SEASON):
        g = fin[fin.season == s][["game_id", "date", "home_id", "away_id"]]
        c = odds.attach(g, raw, "consensus", cw)[["game_id", "home_spread"]]
        f = odds.attach(g, raw, "fanduel", cw)[["game_id", "home_spread"]]
        m = c.merge(f, on="game_id", suffixes=("_c", "_f")).dropna()
        both.append(m.assign(season=s))
    if both:
        m = pd.concat(both)
        d = (m.home_spread_c - m.home_spread_f).abs()
        out += ["", f"Consensus vs FanDuel, same games ({len(m)}): identical {np.mean(d == 0):.1%}, "
                    f"within 0.5 {np.mean(d <= 0.5):.1%}, within 1 {np.mean(d <= 1):.1%}, "
                    f"mean gap {d.mean():.2f} pts.", ""]
    (RESEARCH / "line_audit.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
