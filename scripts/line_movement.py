"""
Does the line move toward the model between the open and the close?

    .venv/bin/python scripts/line_movement.py

Closing line value, measured without results: regress the move from the
opening line to FanDuel's close on the model's disagreement with the opener.
  slope 0   the model knew nothing the opener did not
  slope > 0 the market later moved toward the model: an edge that exists only
            for a bet placed EARLY, before the move (what CLV measures)
Opening lines exist from 2023-24 on, so this runs on the hold-out seasons. It
also reports the model against the opener on results, and the same bet rules
priced at the opening number (spreads at -110, which openers almost always
are; the opening moneylines as posted). Those are looks at hold-out outcomes,
so the run is logged to research/holdout_log.csv.
Writes research/line_movement.md.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from cbb import bets, evaluate, replay
from cbb.config import HOLDOUT_SEASONS, RESEARCH, load_params, season_label


def slope(x, y) -> tuple[float, float, int]:
    x, y = np.asarray(x, float), np.asarray(y, float)
    ok = np.isfinite(x) & np.isfinite(y)
    x, y = x[ok], y[ok]
    X = np.column_stack([np.ones_like(x), x])
    b, *_ = np.linalg.lstsq(X, y, rcond=None)
    r = y - X @ b
    se = np.sqrt(np.diag(np.linalg.pinv(X.T @ X)) * (r @ r) / max(len(y) - 2, 1))
    return float(b[1]), float(b[1] / se[1]), int(ok.sum())


def bets_at_open(pred: pd.DataFrame, params) -> list[str]:
    """The bet rules, unchanged, priced at the opener instead of FanDuel's close."""
    p = pred[pred.open_home_spread.notna()].copy()
    p["open_home_spread_price"] = -110.0
    p["open_away_spread_price"] = -110.0
    res = p.set_index("game_id").result
    q = bets.qualifying(bets.candidates(p, params, prefix="open_"))
    rows = ["Bets at the opening number (same rules, same code, `bets.py`):", "",
            "| bets | record | ROI per $1 | SE | units | model said | won |", "|---|---|---|---|---|---|---|"]
    for label, b in (("every qualifying bet", q), ("the card (8 + 8 a week)", bets.card(q))):
        g = bets.grade(b, res)
        g = g[g.outcome.isin(["W", "L", "P"])]
        if not len(g):
            continue
        dec = g[g.outcome != "P"]
        se = g.profit.std(ddof=1) / np.sqrt(len(g))
        rows.append(f"| {label}: {len(g)} | {(g.outcome == 'W').sum()}-{(g.outcome == 'L').sum()}-"
                    f"{(g.outcome == 'P').sum()} | {g.profit.mean():+.1%} | {se:.1%} | {g.profit.sum():+.1f} | "
                    f"{dec.p_bet.mean():.1%} | {(dec.outcome == 'W').mean():.1%} |")
    return rows


def main():
    params = load_params()
    pred = replay.run(HOLDOUT_SEASONS, params)
    d = pred[(pred.close_book == "fanduel") & pred.open_home_spread.notna() & pred.close_home_spread.notna()].copy()
    d["open_margin"] = -d.open_home_spread
    d["close_margin"] = -d.close_home_spread
    d["move"] = d.close_margin - d.open_margin
    d["disagree"] = d.margin - d.open_margin

    out = ["# Line movement", "", f"Generated by `scripts/line_movement.py` on "
           f"{season_label(HOLDOUT_SEASONS[0])} to {season_label(HOLDOUT_SEASONS[-1])}: the model as it "
           "runs (`data/params.json`), the consensus opening line, FanDuel's closing line.", "",
           "| games | n | line move toward model (slope) | t | model vs opener on results (slope) | t | "
           "model vs FanDuel close on results (slope) | t |", "|---|---|---|---|---|---|---|---|"]
    groups = {"all": d, "bettable (power or ranked)": d[d.bettable]}
    for name, x in groups.items():
        mv = slope(x.disagree, x.move)
        vs_open = slope(x.disagree, x.result - x.open_margin)
        vs_close = slope(x.margin - x.close_margin, x.result - x.close_margin)
        out.append(f"| {name} | {mv[2]} | {mv[0]:+.3f} | {mv[1]:+.1f} | {vs_open[0]:+.3f} | {vs_open[1]:+.1f} | "
                   f"{vs_close[0]:+.3f} | {vs_close[1]:+.1f} |")

    out += ["", "When the model disagreed with the opener by at least this much, how often did the "
            "close move its way (games where the line moved at all):", "",
            "| disagreement | games | moved toward model | moved away | toward share |", "|---|---|---|---|---|"]
    b = d[d.bettable]
    for lo in (1, 2, 3, 4):
        x = b[b.disagree.abs() >= lo]
        moved = x[x.move != 0]
        toward = int((np.sign(moved.move) == np.sign(moved.disagree)).sum())
        away = len(moved) - toward
        share = toward / len(moved) if len(moved) else np.nan
        out.append(f"| {lo}+ points | {len(x)} | {toward} | {away} | {share:.1%} |")
    out += ["", *bets_at_open(pred, params), ""]
    (RESEARCH / "line_movement.md").write_text("\n".join(out) + "\n")
    evaluate.log_holdout("line_movement.py", params)
    print("\n".join(out))


if __name__ == "__main__":
    main()
